# ---------------------------------------------------------------------------
# Model
# ---------------------------------------------------------------------------


@dataclass
class Field:
    name: str
    number: int
    type: str  # scalar name, or fully qualified ".pkg.Name"
    kind: str  # scalar | message | enum | map
    label: str  # singular | optional | repeated | map
    description: str
    oneof: str | None = None
    deprecated: bool = False
    map_key: str | None = None
    map_value: tuple[str, str] | None = None  # (kind, type)


@dataclass
class Message:
    package: str
    name: str
    description: str
    fields: list[Field] = field(default_factory=list)
    oneofs: dict[str, list[str]] = field(default_factory=dict)

    @property
    def full_name(self) -> str:
        return f".{self.package}.{self.name}"


@dataclass
class EnumValue:
    name: str
    number: int
    description: str


@dataclass
class Enum:
    package: str
    name: str
    description: str
    values: list[EnumValue] = field(default_factory=list)

    @property
    def full_name(self) -> str:
        return f".{self.package}.{self.name}"


@dataclass
class Rpc:
    package: str
    service: str
    name: str
    input_type: str
    output_type: str
    description: str

    @property
    def key(self) -> str:
        return f"{self.service}/{self.name}"

    @property
    def grpc_path(self) -> str:
        return f"{self.package}.{self.service}/{self.name}"


@dataclass
class Model:
    rpcs: list[Rpc]
    messages: dict[str, Message]
    enums: dict[str, Enum]


# ---------------------------------------------------------------------------
# Text helpers
# ---------------------------------------------------------------------------

_LIST_ITEM = re.compile(r"^(?:[-*]|\d+[.)])\s+")
_BACKTICK_SPAN = re.compile(r"(`[^`]*`)")


_HYPHEN_WRAP = re.compile(r"[A-Za-z]-$")


def join_wrapped(lines: list[str]) -> str:
    """Join wrapped comment lines, keeping a word hyphenated across a wrap."""
    out = ""
    for line in lines:
        if out and _HYPHEN_WRAP.search(out) and line[:1].islower():
            out += line
        elif out:
            out += " " + line
        else:
            out = line
    return out


def comment_blocks(raw: str | None) -> list[tuple[str, str]]:
    """Split a protoc comment into ``("para" | "item", text)`` blocks."""
    if not raw:
        return []
    blocks: list[tuple[str, str]] = []
    current: list[str] | None = None
    kind = "para"

    def flush() -> None:
        nonlocal current
        if current:
            blocks.append((kind, join_wrapped(current)))
        current = None

    for line in raw.splitlines():
        text = " ".join(line.split())
        if not text:
            flush()
            continue
        if _LIST_ITEM.match(text):
            flush()
            kind = "item"
            current = [text]
        else:
            if current is None:
                kind = "para"
                current = [text]
            else:
                current.append(text)
    flush()
    return blocks


def comment_text(raw: str | None) -> str:
    """Flatten a protoc comment to one line of text."""
    return " ".join(text for _, text in comment_blocks(raw))


def mdx_escape(text: str) -> str:
    """Escape characters that MDX would parse, leaving code spans intact."""
    parts = _BACKTICK_SPAN.split(text)
    out = []
    for index, part in enumerate(parts):
        if index % 2 == 1:
            out.append(part)
            continue
        part = part.replace("{", "\\{").replace("}", "\\}")
        part = part.replace("<", "\\<").replace(">", "\\>")
        out.append(part)
    return "".join(out)


def cell(text: str) -> str:
    """Format text for a Markdown table cell."""
    escaped = mdx_escape(" ".join(text.split()))
    return escaped.replace("|", "\\|") or "-"


def description_markdown(raw: str | None) -> str:
    """Render a protoc comment as Markdown paragraphs and list items."""
    out: list[str] = []
    previous = None
    for kind, text in comment_blocks(raw):
        if out:
            out.append("\n" if kind == "item" and previous == "item" else "\n\n")
        out.append(mdx_escape(text))
        previous = kind
    return "".join(out).replace("\n\n\n", "\n\n").strip()


def first_sentence(text: str) -> str:
    parts = re.split(r"(?<=[.!?])\s+(?=[A-Z])", text.strip(), maxsplit=1)
    return parts[0]


def kebab(name: str) -> str:
    """Convert CamelCase to the kebab-case used in Fern slugs."""
    spaced = re.sub(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Za-z])(?=[0-9])", "-", name)
    return spaced.lower()


def github_slug(heading: str) -> str:
    slug = heading.strip().lower()
    slug = re.sub(r"[^\w\- ]", "", slug)
    return slug.replace(" ", "-")


def native_rpc_url(rpc: Rpc) -> str:
    service = kebab(rpc.service)
    return f"{DOC_ROOT_URL}/{service}/{service}/{service}-{kebab(rpc.name)}"


def rpc_heading(rpc: Rpc) -> str:
    return f"{rpc.name} (V2)" if rpc.service.endswith("V2") else rpc.name


def type_page(package: str) -> str:
    return f"types-{package.replace('_', '-')}.md"


# ---------------------------------------------------------------------------
# Building the model from a buf image
# ---------------------------------------------------------------------------


def find_buf() -> list[str]:
    if shutil.which("buf"):
        return ["buf"]
    if shutil.which("npx"):
        return ["npx", "-y", BUF_NPM_PACKAGE]
    raise ApiReferenceError(
        "buf is required. Install it from https://buf.build/docs/installation "
        "or install Node.js so `npx @bufbuild/buf` works."
    )


def build_image(proto_dir: Path = PROTO_DIR) -> dict:
    command = [*find_buf(), "build", str(proto_dir), "-o", "-#format=json"]
    result = subprocess.run(command, capture_output=True, text=True, check=False)
    if result.returncode != 0:
        raise ApiReferenceError(f"buf build failed:\n{result.stderr.strip()}")
    return json.loads(result.stdout)


def _comments(file_desc: dict) -> dict[tuple[int, ...], tuple[str, str]]:
    table = {}
    for location in file_desc.get("sourceCodeInfo", {}).get("location", []):
        path = tuple(location.get("path", []))
        table[path] = (
            location.get("leadingComments", ""),
            location.get("trailingComments", ""),
        )
    return table


def _field_description(comments: dict, path: tuple[int, ...]) -> str:
    leading, trailing = comments.get(path, ("", ""))
    return " ".join(part for part in (comment_text(leading), comment_text(trailing)) if part)


def _classify(field_desc: dict) -> tuple[str, str]:
    kind = field_desc["type"]
    if kind == "TYPE_MESSAGE":
        return "message", field_desc["typeName"]
    if kind == "TYPE_ENUM":
        return "enum", field_desc["typeName"]
    return "scalar", SCALAR_TYPES[kind]


def build_model(image: dict) -> Model:
    messages: dict[str, Message] = {}
    enums: dict[str, Enum] = {}
    rpcs: list[Rpc] = []

    for file_desc in image["file"]:
        package = file_desc.get("package", "")
        if package.startswith("google."):
            continue
        comments = _comments(file_desc)

        for index, msg in enumerate(file_desc.get("messageType", [])):
            path = (4, index)
            message = Message(
                package=package,
                name=msg["name"],
                description=comment_text(comments.get(path, ("", ""))[0]),
            )
            entries = {
                nested["name"]: nested
                for nested in msg.get("nestedType", [])
                if nested.get("options", {}).get("mapEntry")
            }
            declared = [decl["name"] for decl in msg.get("oneofDecl", [])]
            for field_index, field_desc in enumerate(msg.get("field", [])):
                kind, type_name = _classify(field_desc)
                label = {
                    "LABEL_REPEATED": "repeated",
                    "LABEL_OPTIONAL": "singular",
                }.get(field_desc.get("label", "LABEL_OPTIONAL"), "singular")
                if field_desc.get("proto3Optional"):
                    label = "optional"
                parsed = Field(
                    name=field_desc["name"],
                    number=field_desc["number"],
                    type=type_name,
                    kind=kind,
                    label=label,
                    description=_field_description(comments, (*path, 2, field_index)),
                    deprecated=bool(field_desc.get("options", {}).get("deprecated")),
                )
                entry_name = type_name.rsplit(".", 1)[-1]
                if kind == "message" and label == "repeated" and entry_name in entries:
                    key_desc, value_desc = entries[entry_name]["field"]
                    parsed.kind = "map"
                    parsed.label = "map"
                    parsed.map_key = _classify(key_desc)[1]
                    parsed.map_value = _classify(value_desc)
                if "oneofIndex" in field_desc and not field_desc.get("proto3Optional"):
                    group = declared[field_desc["oneofIndex"]]
                    parsed.oneof = group
                    message.oneofs.setdefault(group, []).append(parsed.name)
                message.fields.append(parsed)
            messages[message.full_name] = message

        for index, enum in enumerate(file_desc.get("enumType", [])):
            path = (5, index)
            parsed_enum = Enum(
                package=package,
                name=enum["name"],
                description=comment_text(comments.get(path, ("", ""))[0]),
            )
            for value_index, value in enumerate(enum.get("value", [])):
                parsed_enum.values.append(
                    EnumValue(
                        name=value["name"],
                        number=value.get("number", 0),
                        description=_field_description(comments, (*path, 2, value_index)),
                    )
                )
            enums[parsed_enum.full_name] = parsed_enum

        for service_index, service in enumerate(file_desc.get("service", [])):
            for method_index, method in enumerate(service.get("method", [])):
                path = (6, service_index, 2, method_index)
                rpcs.append(
                    Rpc(
                        package=package,
                        service=service["name"],
                        name=method["name"],
                        input_type=method["inputType"],
                        output_type=method["outputType"],
                        description=comments.get(path, ("", ""))[0],
                    )
                )
    return Model(rpcs=rpcs, messages=messages, enums=enums)


