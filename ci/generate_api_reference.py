def load_metadata(path: Path = METADATA_FILE) -> dict:
    with path.open("rb") as handle:
        return tomllib.load(handle)


def response_job_path(model: Model, rpc: Rpc) -> str | None:
    """Return the response field path that carries the job ID, if any."""
    response = model.messages.get(rpc.output_type)
    if response is None:
        return None
    names = {f.name: f for f in response.fields}
    if "job_id" in names:
        return "job_id"
    nested = names.get("response")
    if nested is not None and nested.kind == "message":
        inner = model.messages.get(nested.type)
        if inner is not None and any(f.name == "job_id" for f in inner.fields):
            return "response.job_id"
    return None


def check_metadata(model: Model, metadata: dict) -> list[str]:
    problems: list[str] = []
    entries = metadata.get("rpcs", {})
    categories = metadata.get("categories", {})
    known = {rpc.key for rpc in model.rpcs}

    for rpc in model.rpcs:
        if rpc.key not in entries:
            problems.append(
                f"{rpc.key}: no entry in rpc-metadata.toml. Add one that sets "
                "category, execution, and target."
            )
    for key in entries:
        if key not in known:
            problems.append(f"{key}: in rpc-metadata.toml but not in the protos.")

    methods = {rpc.name for rpc in model.rpcs}
    for rpc in model.rpcs:
        entry = entries.get(rpc.key)
        if entry is None:
            continue
        for required in ("category", "execution", "target"):
            if required not in entry:
                problems.append(f"{rpc.key}: missing `{required}`.")
        if entry.get("category") not in categories:
            problems.append(f"{rpc.key}: unknown category `{entry.get('category')}`.")
        execution = entry.get("execution")
        if execution not in EXECUTION_MODES:
            problems.append(f"{rpc.key}: invalid execution `{execution}`.")
        if entry.get("target") not in TARGET_MODES:
            problems.append(f"{rpc.key}: invalid target `{entry.get('target')}`.")

        description = comment_text(rpc.description)
        if execution in ASYNC_MODES:
            poller = entry.get("poll_with")
            if not poller:
                problems.append(f"{rpc.key}: asynchronous RPCs need `poll_with`.")
            elif poller not in methods:
                problems.append(f"{rpc.key}: `poll_with` names unknown RPC `{poller}`.")
            if response_job_path(model, rpc) is None:
                problems.append(
                    f"{rpc.key}: marked {execution}, but the response has no "
                    "`job_id` or `response.job_id` field."
                )
        elif execution == "sync":
            if re.search(r"asynchronous", description, re.IGNORECASE) and not entry.get(
                "override_async_check"
            ):
                problems.append(
                    f"{rpc.key}: marked sync, but its proto comment says it is "
                    "asynchronous. Fix the execution mode, or set "
                    "`override_async_check = true` if the comment only "
                    "describes the jobs it reports on."
                )
        if entry.get("poll_with") and execution not in ASYNC_MODES:
            problems.append(f"{rpc.key}: `poll_with` is only valid for asynchronous RPCs.")

        summary = entry.get("summary") or first_sentence(description)
        if len(summary) > MAX_SUMMARY_CHARS:
            problems.append(
                f"{rpc.key}: first sentence of the proto comment is "
                f"{len(summary)} characters. Add a `summary` of at most "
                f"{MAX_SUMMARY_CHARS} characters in rpc-metadata.toml."
            )
    return problems


def pinned_librms_rev() -> str:
    with CARGO_TOML.open("rb") as handle:
        cargo = tomllib.load(handle)
    dependency = cargo["workspace"]["dependencies"]["librms"]
    rev = dependency.get("rev") if isinstance(dependency, dict) else None
    if not rev:
        raise ApiReferenceError("Cargo.toml does not pin `librms` by `rev`.")
    return rev


def proto_digests() -> dict[str, str]:
    """SHA-256 of each vendored proto, keyed by file name."""
    return {
        path.name: hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(PROTO_DIR.glob("*.proto"))
    }


def render_rev_file(rev: str) -> str:
    """LIBRMS_REV holds the revision, then one `<file>:<sha256>` line per proto."""
    digests = "".join(f"{name}:{digest}\n" for name, digest in proto_digests().items())
    return f"{rev}\n{digests}"


def check_vendored_revision() -> list[str]:
    if not REV_FILE.exists():
        return ["fern/proto/LIBRMS_REV is missing. Run `just api-ref-sync`."]
    lines = REV_FILE.read_text().split()
    vendored = lines[0] if lines else ""
    pinned = pinned_librms_rev()
    if vendored != pinned:
        return [
            f"fern/proto is vendored from librms {vendored}, but Cargo.toml pins "
            f"{pinned}. Run `just api-ref-sync`, then `just api-ref-gen`."
        ]
    recorded = dict(line.split(":", 1) for line in lines[1:] if ":" in line)
    actual = proto_digests()
    problems = []
    for name in sorted(set(recorded) | set(actual)):
        if recorded.get(name) != actual.get(name):
            problems.append(
                f"fern/proto/{name} differs from what `just api-ref-sync` vendored. "
                "Don't edit the vendored protos by hand; run `just api-ref-sync`."
            )
    return problems


