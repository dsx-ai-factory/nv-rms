def link_type(model: Model, kind: str, type_name: str) -> str:
    """Render a message or enum type, linking to its generated section."""
    if type_name in WELL_KNOWN_TYPES:
        return f"`{WELL_KNOWN_TYPES[type_name]}`"
    target = model.messages.get(type_name) or model.enums.get(type_name)
    short = type_name.rsplit(".", 1)[-1]
    if target is None:
        return f"`{short}`"
    return f"[`{short}`]({type_page(target.package)}#{github_slug(short)})"


def field_type_markdown(model: Model, fld: Field) -> str:
    if fld.kind == "map":
        assert fld.map_key is not None and fld.map_value is not None
        value_kind, value_type = fld.map_value
        value = (
            f"`{value_type}`"
            if value_kind == "scalar"
            else link_type(model, value_kind, value_type)
        )
        return f"map of `{fld.map_key}` to {value}"
    base = f"`{fld.type}`" if fld.kind == "scalar" else link_type(model, fld.kind, fld.type)
    if fld.label in {"repeated", "optional"}:
        return f"{fld.label} {base}"
    return base


def field_description_markdown(fld: Field) -> str:
    text = fld.description
    if fld.deprecated and "deprecated" not in text.lower():
        text = f"Deprecated. {text}".strip()
    if fld.oneof:
        text = f"{text} Part of oneof `{fld.oneof}`.".strip()
    return text


def fields_table(model: Model, message: Message) -> list[str]:
    if not message.fields:
        return ["This message has no fields."]
    lines = ["| Field | Type | Description |", "| --- | --- | --- |"]
    for fld in message.fields:
        lines.append(
            f"| `{fld.name}` | {field_type_markdown(model, fld)} "
            f"| {cell(field_description_markdown(fld))} |"
        )
    return lines


def example_value(model: Model, fld: Field, depth: int, seen: tuple[str, ...]):
    def one(kind: str, type_name: str):
        if kind == "scalar":
            if type_name in {"string"}:
                return f"<{fld.name}>"
            if type_name == "bool":
                return False
            if type_name == "bytes":
                return ""
            if type_name in {"double", "float"}:
                return 0.0
            return 0
        if kind == "enum":
            enum = model.enums.get(type_name)
            if enum is None:
                return 0
            values = [v for v in enum.values if v.number != 0] or enum.values
            return values[0].name if values else 0
        if type_name in WELL_KNOWN_TYPES:
            return "2026-01-01T00:00:00Z"
        return example_message(model, type_name, depth + 1, seen)

    if fld.kind == "map":
        assert fld.map_value is not None
        return {"<key>": one(*fld.map_value)}
    value = one(fld.kind, fld.type)
    return [value] if fld.label == "repeated" else value


def example_message(
    model: Model, type_name: str, depth: int = 0, seen: tuple[str, ...] = ()
) -> dict:
    message = model.messages.get(type_name)
    if message is None or depth > EXAMPLE_MAX_DEPTH or type_name in seen:
        return {}
    result: dict = {}
    used_oneofs: set[str] = set()
    for fld in message.fields:
        if fld.deprecated:
            continue
        if fld.oneof:
            if fld.oneof in used_oneofs:
                continue
            used_oneofs.add(fld.oneof)
        result[fld.name] = example_value(model, fld, depth, (*seen, type_name))
    return result


def render_example(model: Model, rpc: Rpc, entry: dict) -> list[str]:
    payload = json.dumps(example_message(model, rpc.input_type), indent=2)
    intro = (
        "Replace each `<placeholder>` with a real value. Define "
        if "<" in payload
        else "Define "
    )
    lines = [
        "<Accordion title=\"Example request\">",
        "",
        f"{intro}`RMS_GRPCURL_FLAGS` and `RMS_ADDR` as described in "
        "[Getting started](../getting-started.md#call-an-rpc-with-grpcurl).",
        "",
        "```bash",
        "grpcurl $RMS_GRPCURL_FLAGS \\",
        f"  -d '{payload}' \\",
        f"  \"$RMS_ADDR\" {rpc.grpc_path}",
        "```",
    ]
    command = entry.get("client_command")
    if command:
        lines += [
            "",
            "The `rack_manager_client` test client offers an equivalent command:",
            "",
            "```bash",
            f"rack_manager_client <host> <port> {command}",
            "```",
        ]
    lines += ["", "</Accordion>"]
    return lines


def rpc_summary(rpc: Rpc, entry: dict) -> str:
    return entry.get("summary") or first_sentence(comment_text(rpc.description))


def poll_link(model: Model, poller: str) -> str:
    owner = next(rpc for rpc in model.rpcs if rpc.name == poller)
    return f"[`{poller}`]({rpc_page_ref(owner)})"


def rpc_page_ref(rpc: Rpc) -> str:
    """Relative link to an RPC section on its generated category page."""
    category = _CATEGORY_BY_RPC.get(rpc.key)
    anchor = github_slug(rpc_heading(rpc))
    return f"{category}.md#{anchor}"


# Filled by `generate_pages` so link helpers can resolve categories.
_CATEGORY_BY_RPC: dict[str, str] = {}


def render_rpc(model: Model, rpc: Rpc, entry: dict) -> list[str]:
    execution = entry["execution"]
    exec_title, exec_text = EXECUTION_MODES[execution]
    target_title, target_text = TARGET_MODES[entry["target"]]
    response = model.messages[rpc.output_type]
    request = model.messages[rpc.input_type]

    lines = [f"## {rpc_heading(rpc)}", ""]
    lines += [f"`{rpc.grpc_path}`", ""]
    lines += [description_markdown(rpc.description), ""]

    if entry.get("note"):
        lines += ["<Warning>", mdx_escape(entry["note"]), "</Warning>", ""]

    lines += ["| Property | Value |", "| --- | --- |"]
    lines.append(f"| Execution | **{exec_title}.** {cell(exec_text)} |")
    if execution in ASYNC_MODES:
        job_path = response_job_path(model, rpc)
        poller = entry["poll_with"]
        text = (
            f"Poll {poll_link(model, poller)} with the job ID in "
            f"`{job_path}`."
        )
        has_jobs = any(f.name == "jobs" for f in response.fields)
        if execution == "async-batch":
            text += (
                " Per-node child job IDs are in `jobs`."
                if has_jobs
                else " Set `include_child_job_states` on `GetJobStatus` to "
                "read per-node child jobs."
            )
        lines.append(f"| Job tracking | {text} |")
        if entry.get("result_json"):
            lines.append(
                f"| Job result | `result_json` in the job status holds "
                f"{cell(entry['result_json'])}. |"
            )
    lines.append(f"| Target | **{target_title}.** {cell(target_text)} |")
    if entry.get("operations_page"):
        page = entry["operations_page"]
        lines.append(f"| Behavior details | [Operations guide](../../{page}) |")
    lines.append(f"| Protobuf reference | [`{rpc.name}`]({native_rpc_url(rpc)}) |")
    lines.append("")

    lines += [f"**Request:** [`{request.name}`]({type_page(request.package)}#{github_slug(request.name)})", ""]
    lines += [*fields_table(model, request), ""]
    lines += [f"**Response:** [`{response.name}`]({type_page(response.package)}#{github_slug(response.name)})", ""]
    lines += [*fields_table(model, response), ""]

    errors = entry.get("grpc_errors", {})
    lines.append(
        "**Errors:** Refer to [Conventions](../conventions.md#error-handling) "
        "for how RMS reports failures."
        + (" This RPC also returns these gRPC errors:" if errors else "")
    )
    if errors:
        lines.append("")
        for code, condition in errors.items():
            lines.append(f"- `{code}`: {mdx_escape(' '.join(condition.split()))}")
    lines += ["", *render_example(model, rpc, entry), ""]
    return lines


def render_category(model: Model, key: str, info: dict, metadata: dict) -> str:
    rpcs = [
        rpc
        for rpc in model.rpcs
        if metadata["rpcs"][rpc.key]["category"] == key
    ]
    rpcs.sort(key=lambda r: list(metadata["rpcs"]).index(r.key))
    lines = [f"# {info['title']}", "", GENERATED_NOTICE, "", info["summary"], ""]
    lines += ["| RPC | Execution | Summary |", "| --- | --- | --- |"]
    for rpc in rpcs:
        entry = metadata["rpcs"][rpc.key]
        lines.append(
            f"| [`{rpc_heading(rpc)}`](#{github_slug(rpc_heading(rpc))}) "
            f"| {EXECUTION_MODES[entry['execution']][0]} "
            f"| {cell(rpc_summary(rpc, entry))} |"
        )
    lines.append("")
    lines += [
        "For definitions of execution modes and job polling, refer to "
        "[Async jobs](../async-jobs.md).",
        "",
    ]
    for rpc in rpcs:
        lines += render_rpc(model, rpc, metadata["rpcs"][rpc.key])
    return "\n".join(lines).rstrip() + "\n"


def render_catalog(model: Model, metadata: dict) -> str:
    lines = [
        "# RPC catalog",
        "",
        GENERATED_NOTICE,
        "",
        f"RMS exposes {len(model.rpcs)} RPCs across two gRPC services. Use this "
        "table to find an RPC and to see at a glance whether it returns its "
        "result directly or returns a job ID that you poll.",
        "",
        "For what each execution mode means, refer to [Async jobs](../async-jobs.md).",
        "",
        "| RPC Method | Service | Execution | Poll with | Target |",
        "| --- | --- | --- | --- | --- |",
    ]
    order = list(metadata["rpcs"])
    categories = list(metadata["categories"])
    ordered = sorted(
        model.rpcs,
        key=lambda r: (
            categories.index(metadata["rpcs"][r.key]["category"]),
            order.index(r.key),
        ),
    )
    for rpc in ordered:
        entry = metadata["rpcs"][rpc.key]
        poller = entry.get("poll_with")
        poll_cell = poll_link(model, poller) if poller else "-"
        lines.append(
            f"| [`{rpc_heading(rpc)}`]({rpc_page_ref(rpc)}) "
            f"| `{rpc.service}` "
            f"| {EXECUTION_MODES[entry['execution']][0]} "
            f"| {poll_cell} "
            f"| {TARGET_MODES[entry['target']][0]} |"
        )
    lines.append("")
    return "\n".join(lines)


def render_types(model: Model, package: str) -> str:
    service = next((r.service for r in model.rpcs if r.package == package), package)
    lines = [
        f"# {service} types",
        "",
        GENERATED_NOTICE,
        "",
        f"Messages and enums in the `{package}` protobuf package. Proto3 has no "
        "required fields, so a field that an RPC needs says so in its "
        "description. Refer to [Conventions](../conventions.md#node-identity) "
        "for how nodes are described.",
        "",
        "## Messages",
        "",
    ]
    for message in sorted(
        (m for m in model.messages.values() if m.package == package),
        key=lambda m: m.name,
    ):
        lines += [f"### {message.name}", ""]
        if message.description:
            lines += [mdx_escape(message.description), ""]
        lines += [*fields_table(model, message), ""]
        for group, members in message.oneofs.items():
            names = ", ".join(f"`{n}`" for n in members)
            lines += [f"Set at most one of {names} (oneof `{group}`).", ""]

    enums = sorted(
        (e for e in model.enums.values() if e.package == package),
        key=lambda e: e.name,
    )
    if enums:
        lines += ["## Enums", ""]
    for enum in enums:
        lines += [f"### {enum.name}", ""]
        if enum.description:
            lines += [mdx_escape(enum.description), ""]
        lines += ["| Value | Number | Description |", "| --- | --- | --- |"]
        for value in enum.values:
            lines.append(f"| `{value.name}` | {value.number} | {cell(value.description)} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def generate_pages(model: Model, metadata: dict) -> dict[str, str]:
    _CATEGORY_BY_RPC.clear()
    for rpc in model.rpcs:
        entry = metadata["rpcs"].get(rpc.key)
        if entry:
            _CATEGORY_BY_RPC[rpc.key] = entry["category"]
    pages = {"rpc-catalog.md": render_catalog(model, metadata)}
    for key, info in metadata["categories"].items():
        pages[f"{key}.md"] = render_category(model, key, info, metadata)
    for package in sorted({rpc.package for rpc in model.rpcs}):
        pages[type_page(package)] = render_types(model, package)
    return pages


